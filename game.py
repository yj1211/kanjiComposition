    def _build_promotion_tree_text(self, character: str) -> str:
        return "\n".join(self._build_promotion_lines(character, set(), is_root=True))

    def _build_promotion_lines(
        self,
        character: str,
        visiting: set[str],
        *,
        prefix: str = "",
        is_last: bool = True,
        is_root: bool = False,
    ) -> list[str]:
        label = character if is_root else f"{prefix}{'└─ ' if is_last else '├─ '}{character}"

        if character in visiting:
            return [f"{label} (循環略過)"]

        next_results = self.ingredient_to_results.get(character, [])
        if not next_results:
            if is_root:
                return [character, "└─ 目前沒有可繼續推廣的字"]
            return [label]

        lines = [label]
        next_visiting = set(visiting)
        next_visiting.add(character)
        next_prefix = prefix + ("   " if is_last else "│  ")

        for index, result in enumerate(next_results):
            lines.extend(
                self._build_promotion_lines(
                    result,
                    next_visiting,
                    prefix=next_prefix,
                    is_last=index == len(next_results) - 1,
                    is_root=False,
                )
            )
        return lines

    def _collect_promotion_descendants(self, character: str) -> set[str]:
        collected: set[str] = set()
        stack = list(self.ingredient_to_results.get(character, []))

        while stack:
            current = stack.pop()
            if current in collected:
                continue
            collected.add(current)
            stack.extend(self.ingredient_to_results.get(current, []))

        return collected

    def _build_recipe_tree_text(self, character: str) -> str:
        return "\n".join(self._build_tree_lines(character, set(), is_root=True))

    def _build_tree_lines(
        self,
        character: str,
        visiting: set[str],
        *,
        prefix: str = "",
        is_last: bool = True,
        is_root: bool = False,
    ) -> list[str]:
        label = character if is_root else f"{prefix}{'└─ ' if is_last else '├─ '}{character}"

        if character in self.STARTERS:
            return [label]

        if character in visiting:
            return [f"{label} (循環略過)"]

        ingredient_options = self.result_to_ingredients.get(character)
        if not ingredient_options:
            return [f"{label} (無已知配方)"]

        best_ingredients = self._choose_best_recipe(character, visiting)
        next_prefix = prefix + ("   " if is_last else "│  ")
        lines = [label]
        next_visiting = set(visiting)
        next_visiting.add(character)

        for index, ingredient in enumerate(best_ingredients):
            lines.extend(
                self._build_tree_lines(
                    ingredient,
                    next_visiting,
                    prefix=next_prefix,
                    is_last=index == len(best_ingredients) - 1,
                    is_root=False,
                )
            )
        return lines

    def _choose_best_recipe(self, character: str, visiting: set[str]) -> tuple[str, ...]:
        ingredient_options = self.result_to_ingredients.get(character, [])
        best_option = ingredient_options[0]
        best_score = self._score_recipe_option(best_option, visiting | {character})

        for option in ingredient_options[1:]:
            option_score = self._score_recipe_option(option, visiting | {character})
            if option_score < best_score:
                best_option = option
                best_score = option_score

        return best_option

    def _score_recipe_option(
        self,
        ingredients: tuple[str, ...],
        visiting: set[str],
    ) -> tuple[int, int, tuple[str, ...]]:
        total_cost = 0
        for ingredient in ingredients:
            total_cost += self._score_character_cost(ingredient, visiting)
        return (total_cost, len(ingredients), ingredients)

    def _score_character_cost(self, character: str, visiting: set[str]) -> int:
        if character in self.STARTERS:
            return 1
        if character in visiting:
            return 9999

        ingredient_options = self.result_to_ingredients.get(character)
        if not ingredient_options:
            return 9999

        next_visiting = set(visiting)
        next_visiting.add(character)
        return 1 + min(
            sum(self._score_character_cost(part, next_visiting) for part in option)
            for option in ingredient_options
        )

